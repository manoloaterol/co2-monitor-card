#!/usr/bin/env python3
"""Regenerates the glyph block of co2-monitor-card.js from the TTF files.

The card draws text as SVG paths taken from the same fonts the monitor uses, so
it needs no web font and looks the same offline. Each text style mirrors one
bitmap font of the firmware (components/display/fonts.c) and is sized with the
rules of the firmware's tools/font_gen/gen_font.py:

  - the digit '0' fills the cell height minus 2 rows on top and 2 below;
  - the set is condensed in x just enough for the widest digit to fit the cell,
    leaving 1 blank column;
  - every glyph is centered by its ink in a fixed-width cell.

Usage:  gen_glyphs.py <dir with the TTFs> [card.js]

The TTFs come from https://github.com/google/fonts (ofl/goldman, ofl/russoone).
Needs fontTools.
"""
import json
import re
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

DIGITS = "0123456789"

# key -> (file, characters it must carry)
FONTS = {
    "gb": ("Goldman-Bold.ttf", DIGITS + "ABCDEFGHIJKLMNOPQRSTUVWXYZpm-.%°"),
    "gr": ("Goldman-Regular.ttf", DIGITS + "-"),
    "ru": ("RussoOne-Regular.ttf", DIGITS + "-"),
}

# key -> (font, cell width, cell height), one per bitmap font of the firmware
STYLES = {
    "g13": ("gb", 13, 13),
    "g16": ("gb", 16, 16),
    "g20": ("gb", 20, 20),
    "g32": ("gb", 32, 30),
    "r15": ("gr", 15, 17),
    "ru90": ("ru", 58, 90),
}

GAP = 1   # blank columns right of the widest digit, as in gen_font.py


def load(path, chars):
    font = TTFont(path)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    glyphs = {}
    for ch in chars:
        name = cmap.get(ord(ch))
        if name is None:
            sys.exit(f"{path.name} has no glyph for {ch!r}")
        bp = BoundsPen(gs)
        gs[name].draw(bp)
        if bp.bounds is None:
            continue
        sp = SVGPathPen(gs, ntos=lambda v: f"{v:g}")
        gs[name].draw(sp)
        x0, y0, x1, y1 = bp.bounds
        glyphs[ch] = [round(x0), round(y0), round(x1), round(y1), sp.getCommands()]
    return glyphs


def style(glyphs, cell_w, cell_h):
    _, y0, _, y1, _ = glyphs["0"]
    s = (cell_h - 4) / (y1 - y0)                    # '0' spans rows 2..h-3
    widest = max(glyphs[d][2] - glyphs[d][0] for d in DIGITS) * s
    xs = min(1.0, (cell_w - GAP) / widest)
    base = 2 + y1 * s                               # baseline below the cell top
    return {"w": cell_w, "h": cell_h, "s": round(s, 6), "xs": round(xs, 4),
            "base": round(base, 3)}


def main():
    src = Path(sys.argv[1])
    card = Path(sys.argv[2]) if len(sys.argv) > 2 else \
        Path(__file__).resolve().parent.parent / "co2-monitor-card.js"

    fonts = {k: load(src / f, chars) for k, (f, chars) in FONTS.items()}
    styles = {k: dict(style(fonts[f], w, h), f=f) for k, (f, w, h) in STYLES.items()}

    block = (
        "// BEGIN GLYPHS: generated by tools/gen_glyphs.py, do not edit by hand.\n"
        "// Outlines from Goldman (c) The Goldman Project Authors and Russo One (c)\n"
        "// Jovanny Lemonad, both under the SIL Open Font License 1.1 (see fonts/).\n"
        "// Per glyph: [xMin, yMin, xMax, yMax, path], in font units, y up.\n"
        f"const FONTS = {json.dumps(fonts, ensure_ascii=False, separators=(',', ':'))};\n"
        f"const STYLES = {json.dumps(styles, separators=(',', ':'))};\n"
        "// END GLYPHS"
    )

    text = card.read_text()
    new, n = re.subn(r"// BEGIN GLYPHS.*?// END GLYPHS", lambda _: block, text, flags=re.S)
    if n != 1:
        sys.exit(f"{card.name}: glyph markers not found")
    card.write_text(new)
    print(f"{card.name}: {len(block)} bytes of glyphs", file=sys.stderr)


if __name__ == "__main__":
    main()
